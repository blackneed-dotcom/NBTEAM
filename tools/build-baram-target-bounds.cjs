// Read existing RGBA PNGs without changing them; bake opaque bounds for targeting.
const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'RootDesk/MyDesk/BaramWorld/BaramCreatureData.mlua'), 'utf8');
const refs = new Set(source.match(/[0-9a-f]{32}/g));
const rows = JSON.parse(fs.readFileSync(path.join(root, 'Docs/BaramSource/actor-ruids.json'), 'utf8'));
function bounds(file) {
  const png = fs.readFileSync(file), chunks = [];
  const w = png.readUInt32BE(16), h = png.readUInt32BE(20);
  if (png[24] !== 8 || png[25] !== 6 || png[28] !== 0) throw Error('Expected non-interlaced RGBA8: ' + file);
  for (let p = 8; p < png.length;) {
    const n = png.readUInt32BE(p), type = png.toString('ascii', p + 4, p + 8);
    if (type === 'IDAT') chunks.push(png.subarray(p + 8, p + 8 + n));
    p += n + 12;
  }
  const raw = zlib.inflateSync(Buffer.concat(chunks)), stride = w * 4;
  if (raw.length !== h * (stride + 1)) throw Error('Unexpected PNG size');
  const pixels = Buffer.alloc(h * stride);
  const paeth = (a, b, c) => {
    const p = a + b - c, da = Math.abs(p - a), db = Math.abs(p - b), dc = Math.abs(p - c);
    return da <= db && da <= dc ? a : db <= dc ? b : c;
  };
  let left = w, top = h, right = 0, bottom = 0;
  for (let y = 0; y < h; y++) {
    const filter = raw[y * (stride + 1)];
    if (filter > 4) throw Error('Invalid PNG filter');
    for (let x = 0; x < stride; x++) {
      const i = y * stride + x, a = x >= 4 ? pixels[i - 4] : 0;
      const b = y > 0 ? pixels[i - stride] : 0, c = x >= 4 && y > 0 ? pixels[i - stride - 4] : 0;
      pixels[i] = (raw[y * (stride + 1) + x + 1] + [0, a, b, Math.floor((a + b) / 2), paeth(a, b, c)][filter]) & 255;
    }
    for (let x = 0; x < w; x++) if (pixels[y * stride + x * 4 + 3] > 0) {
      left = Math.min(left, x); top = Math.min(top, y);
      right = Math.max(right, x + 1); bottom = Math.max(bottom, y + 1);
    }
  }
  if (right <= left || bottom <= top) throw Error('Empty actor: ' + file);
  // Actor uploads use the default centered pivot and 100 pixels per world unit.
  return [left - w / 2, h / 2 - bottom, right - w / 2, h / 2 - top];
}
const entries = [...refs].sort().map(ruid => {
  const row = rows.find(r => r.ruid === ruid);
  if (!row) throw Error('Unmapped actor sprite: ' + ruid);
  return { ruid, name: row.name, rect: bounds(path.join(root, 'Docs/BaramSource/Assets', row.name + '.png')) };
});
const out = ['-- Generated by tools/build-baram-target-bounds.cjs from the original PNG alpha channel.',
  '@Logic', 'script BaramTargetBounds extends Logic',
  '    -- Pixel bounds relative to the centered sprite pivot: left, bottom, right, top.',
  '    property table Frames = {',
  ...entries.map(e => `        ["${e.ruid}"] = {${e.rect.join(', ')}},`),
  '    }', 'end', ''].join('\n');
fs.writeFileSync(path.join(root, 'RootDesk/MyDesk/BaramWorld/BaramTargetBounds.mlua'), out);
console.log(JSON.stringify({frames: entries.length, samples: entries.filter(e => ['actor26-414', 'actor22-322'].includes(e.name))}));
