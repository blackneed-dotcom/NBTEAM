const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const fields = 'id,name,type,imageId,equipImageId,dye,maxCount,durability,price,strengthRequired,dexterityRequired,intelligenceRequired,genderRequired,levelRequired,jobRequired,promotionRequired,deathType,dropAllowed,repairable,repairCost,depositCost,renameCost,equipScript,unequipScript,useScript,tooltip,description,attack'.split(',');
const items = {}, icons = {}, warnings = [];
const assets = JSON.parse(fs.readFileSync(path.join(root,'Docs/BaramResourcePack/resource-map.json'),'utf8')).assets;
const lua = v => v == null ? 'nil' : typeof v === 'string' ? JSON.stringify(v) : typeof v === 'object' ? '{' + Object.entries(v).map(([k,x]) => '['+JSON.stringify(k)+'] = '+lua(x)).join(', ') + '}' : String(v);
fs.readFileSync(path.join(root,'item2_db.txt'),'utf8').split(/\r?\n/).forEach((line,index) => {
  if (!/^\d+\t/.test(line)) return;
  const raw = line.split('\t');
  const columns = [...raw];
  while (columns[columns.length-1] === '') columns.pop();
  if (columns.length === 29 && ['1438','1639','1640'].includes(columns[0]) && columns[26] === '-') {
    columns.splice(26,1); warnings.push({id:columns[0],line:index+1,reason:'Extra empty description column normalized'});
  }
  if (columns.length === 27) warnings.push({id:columns[0],line:index+1,reason:'Attack absent in source'});
  else if (columns.length !== fields.length) throw Error('Unexpected column count at line '+(index+1));
  const entry = {};
  columns.forEach((v,i) => {entry[fields[i]] = i === 1 || (i >= 22 && i <= 26) ? v : Number(v); if(typeof entry[fields[i]] === 'number' && !Number.isFinite(entry[fields[i]])) throw Error('Invalid number');});
  if(items[entry.id]) throw Error('Duplicate ID '+entry.id);
  entry.source = {file:'item2_db.txt',line:index+1};
  items[entry.id] = entry;
  const art = assets.find(a => a.subcategory === 'item' && a.source.frame === entry.imageId-1 && a.source.dye === entry.dye);
  if(art) icons[entry.id] = {ruid:art.ruid,width:art.source.width,height:art.source.height};
  else warnings.push({id:entry.id,reason:'No resource for image/dye',imageId:entry.imageId,dye:entry.dye});
});
if(Object.keys(items).length !== 154) throw Error('Expected all 154 source records');
fs.writeFileSync(path.join(root,'RootDesk/MyDesk/BaramWorld/BaramItem2Data.mlua'),'-- Generated by tools/import-baram-item2.cjs; source fields preserved.\n@Logic\nscript BaramItem2Data extends Logic\n    property table Items = '+lua(items)+'\nend\n');
const inputPath = path.join(root,'RootDesk/MyDesk/BaramWorld/BaramInput.mlua');
let input = fs.readFileSync(inputPath,'utf8');
const old = input.match(/    property table InventoryImages = ([^\r\n]+)/);
if(!old) throw Error('InventoryImages declaration not found');
const merged = {};
for(const m of old[1].matchAll(/\["(\d+)"\]\s*=\s*\{\s*(?:\["ruid"\]|ruid)\s*=\s*"([a-f0-9]+)",\s*(?:\["width"\]|width)\s*=\s*(\d+),\s*(?:\["height"\]|height)\s*=\s*(\d+)\s*\}/g)) merged[m[1]]={ruid:m[2],width:Number(m[3]),height:Number(m[4])};
if(!Object.keys(merged).length) throw Error('No previous icons parsed');
for(const id of Object.keys(items)) delete merged[id];
Object.assign(merged,icons);
input = input.replace(old[0],'    property table InventoryImages = '+lua(merged));
fs.writeFileSync(inputPath,input);
fs.writeFileSync(path.join(root,'Docs/BaramSource/item2-import-report.json'),JSON.stringify({source:'item2_db.txt',records:Object.keys(items).length,icons:Object.keys(icons).length,warnings},null,2)+'\n');
console.log(JSON.stringify({records:Object.keys(items).length,icons:Object.keys(icons).length,warnings},null,2));
